class TestSlidingWindow:
    def test_events_between_yields_correct_range(self, tmp_path: Path) -> None:
        """Events outside the query range must not be yielded."""
        events_dir = tmp_path / "idc_events"
        t_before = datetime(2026, 3, 1, 8, 0, tzinfo=UTC)
        t_inside = datetime(2026, 3, 1, 9, 0, tzinfo=UTC)
        t_after = datetime(2026, 3, 1, 10, 0, tzinfo=UTC)

        rows = [
            _make_event_row(t_before, order_id="before"),
            _make_event_row(t_inside, order_id="inside"),
            _make_event_row(t_after, order_id="after"),
        ]
        path = events_dir / "NO1_2026_03.parquet"
        _write_parquet(path, rows, rows_per_rg=3)

        manifest = DataManifest(data_dir=tmp_path, zone="NO1")
        window = SlidingWindow(manifest, lookback=timedelta(hours=4), lookahead=timedelta(hours=1))
        # advance_to t_inside so the row group [t_before, t_after] is within the window
        window.advance_to(t_inside)

        q_start = t_inside - timedelta(minutes=1)
        q_end = t_inside + timedelta(minutes=1)
        events = list(window.events_between(q_start, q_end))
        # "inside" row has timestamp == t_inside which is in [t_inside - 1min, t_inside + 1min)
        assert len(events) == 1

    def test_events_sorted_by_timestamp(self, tmp_path: Path) -> None:
        events_dir = tmp_path / "idc_events"
        base = datetime(2026, 3, 1, 9, 0, tzinfo=UTC)
        rows = [
            _make_event_row(base + timedelta(minutes=2), order_id="c"),
            _make_event_row(base + timedelta(minutes=0), order_id="a"),
            _make_event_row(base + timedelta(minutes=1), order_id="b"),
        ]
        path = events_dir / "NO1_2026_03.parquet"
        _write_parquet(path, rows, rows_per_rg=3)

        manifest = DataManifest(data_dir=tmp_path, zone="NO1")
        window = SlidingWindow(manifest)
        window.advance_to(base)

        events = list(window.events_between(base, base + timedelta(minutes=5)))
        assert len(events) == 3
        for i in range(len(events) - 1):
            assert events[i].timestamp <= events[i + 1].timestamp

    def test_advance_loads_new_row_groups(self, tmp_path: Path) -> None:
        events_dir = tmp_path / "idc_events"
        t0 = datetime(2026, 3, 1, 0, 0, tzinfo=UTC)
        t1 = datetime(2026, 3, 1, 6, 0, tzinfo=UTC)

        rows_rg1 = [_make_event_row(t0, order_id="rg1")]
        rows_rg2 = [_make_event_row(t1, order_id="rg2")]
        path = events_dir / "NO1_2026_03.parquet"
        _write_parquet(path, rows_rg1 + rows_rg2, rows_per_rg=1)

        manifest = DataManifest(data_dir=tmp_path, zone="NO1")
        window = SlidingWindow(manifest, lookback=timedelta(hours=1), lookahead=timedelta(hours=1))

        # At t0 + 30 min, only first RG should be in window
        window.advance_to(t0 + timedelta(minutes=30))
        events_first = list(window.events_between(t0, t0 + timedelta(minutes=30)))
        assert any(isinstance(e, (MarketDataUpdate, HistoricalTrade)) for e in events_first)

        # At t1, second RG should be loaded too
        window.advance_to(t1)
        events_second = list(
            window.events_between(t1 - timedelta(minutes=1), t1 + timedelta(minutes=1))
        )
        assert len(events_second) == 1

    def test_eviction_reduces_memory(self, tmp_path: Path) -> None:
        events_dir = tmp_path / "idc_events"
        t0 = datetime(2026, 3, 1, 0, 0, tzinfo=UTC)
        t6 = datetime(2026, 3, 1, 6, 0, tzinfo=UTC)
        t12 = datetime(2026, 3, 1, 12, 0, tzinfo=UTC)

        rows = (
            [_make_event_row(t0 + timedelta(minutes=i), order_id=f"rg1-{i}") for i in range(5)]
            + [_make_event_row(t6 + timedelta(minutes=i), order_id=f"rg2-{i}") for i in range(5)]
            + [_make_event_row(t12 + timedelta(minutes=i), order_id=f"rg3-{i}") for i in range(5)]
        )
        path = events_dir / "NO1_2026_03.parquet"
        _write_parquet(path, rows, rows_per_rg=5)

        manifest = DataManifest(data_dir=tmp_path, zone="NO1")
        window = SlidingWindow(manifest, lookback=timedelta(hours=1), lookahead=timedelta(hours=1))

        # Load all three row groups
        window.advance_to(t0)
        window.advance_to(t6)
        window.advance_to(t12)
        mem_at_peak = window.memory_usage_bytes

        # Advance far enough to evict first two row groups
        window.advance_to(t12 + timedelta(hours=6))
        mem_after_eviction = window.memory_usage_bytes

        assert mem_after_eviction < mem_at_peak

    def test_memory_usage_bytes_zero_before_advance(self, tmp_path: Path) -> None:
        events_dir = tmp_path / "idc_events"
        t = datetime(2026, 3, 1, 9, 0, tzinfo=UTC)
        path = events_dir / "NO1_2026_03.parquet"
        _write_parquet(path, [_make_event_row(t)], rows_per_rg=1)

        manifest = DataManifest(data_dir=tmp_path, zone="NO1")
        window = SlidingWindow(manifest)
        assert window.memory_usage_bytes == 0

