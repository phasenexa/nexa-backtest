IDC_SCHEMA = IDC_EVENTS_SCHEMA


def _make_event_row(
    ts: datetime,
    product_id: str = "NO1-QH-0900",
    event_type: str = "new",
    order_id: str = "order-1",
    side: str = "buy",
    price: float = 50.0,
    volume: float = 10.0,
    remaining: float = 10.0,
    aggressor_side: str | None = None,
    trade_id: str | None = None,
) -> dict[str, object]:
    return {
        "timestamp": ts,
        "event_type": event_type,
        "order_id": order_id,
        "zone": "NO1",
        "product_id": product_id,
        "side": side,
        "price_eur_mwh": price,
        "volume_mw": volume,
        "remaining_mw": remaining,
        "aggressor_side": aggressor_side,
        "trade_id": trade_id,
    }


def _write_parquet(path: Path, rows: list[dict[str, object]], rows_per_rg: int) -> None:
    """Write a multi-row-group Parquet file from a list of row dicts."""
    df = pd.DataFrame(rows)
    df["timestamp"] = pd.to_datetime(df["timestamp"], utc=True)
    table = pa.Table.from_pandas(df, schema=IDC_SCHEMA, preserve_index=False)

    path.parent.mkdir(parents=True, exist_ok=True)
    writer = pq.ParquetWriter(path, schema=IDC_SCHEMA)
    for start in range(0, len(table), rows_per_rg):
        writer.write_table(table.slice(start, rows_per_rg))
    writer.close()


