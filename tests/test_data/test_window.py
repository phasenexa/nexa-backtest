class TestDataManifest:
    def test_missing_directory_raises(self, tmp_path: Path) -> None:
        with pytest.raises(FileNotFoundError, match="idc_events"):
            DataManifest(data_dir=tmp_path, zone="NO1")

    def test_builds_from_fixture(self, fixture_parquet_path: Path) -> None:
        manifest = DataManifest(data_dir=FIXTURE_DIR, zone="NO1")
        assert len(manifest.row_groups) > 0

    def test_row_groups_sorted_by_min_timestamp(self, fixture_parquet_path: Path) -> None:
        manifest = DataManifest(data_dir=FIXTURE_DIR, zone="NO1")
        rgs = manifest.row_groups
        for i in range(len(rgs) - 1):
            assert rgs[i].min_timestamp <= rgs[i + 1].min_timestamp

    def test_row_groups_for_range_returns_overlapping(self, tmp_path: Path) -> None:
        events_dir = tmp_path / "idc_events"
        t0 = datetime(2026, 3, 1, 0, 0, tzinfo=UTC)
        t1 = datetime(2026, 3, 1, 4, 0, tzinfo=UTC)
        t2 = datetime(2026, 3, 1, 8, 0, tzinfo=UTC)
        t3 = datetime(2026, 3, 1, 12, 0, tzinfo=UTC)

        # Two row groups: [t0, t1) and [t2, t3)
        rows_rg1 = [
            _make_event_row(t0, order_id="a"),
            _make_event_row(t1 - timedelta(seconds=1), order_id="b"),
        ]
        rows_rg2 = [
            _make_event_row(t2, order_id="c"),
            _make_event_row(t3 - timedelta(seconds=1), order_id="d"),
        ]
        path = events_dir / "NO1_2026_03.parquet"
        _write_parquet(path, rows_rg1 + rows_rg2, rows_per_rg=2)

        manifest = DataManifest(data_dir=tmp_path, zone="NO1")
        assert len(manifest.row_groups) == 2

        # Query range entirely within first RG
        refs = manifest.row_groups_for_range(t0, t0 + timedelta(hours=2))
        assert len(refs) == 1

        # Query range spanning both RGs
        refs = manifest.row_groups_for_range(t0, t3)
        assert len(refs) == 2

        # Query range before any data
        refs = manifest.row_groups_for_range(t0 - timedelta(hours=2), t0 - timedelta(hours=1))
        assert len(refs) == 0

    def test_row_group_ref_fields(self, tmp_path: Path) -> None:
        events_dir = tmp_path / "idc_events"
        t = datetime(2026, 3, 1, 6, 0, tzinfo=UTC)
        rows = [_make_event_row(t)]
        path = events_dir / "NO1_2026_03.parquet"
        _write_parquet(path, rows, rows_per_rg=1)

        manifest = DataManifest(data_dir=tmp_path, zone="NO1")
        ref = manifest.row_groups[0]
        assert isinstance(ref, RowGroupRef)
        assert ref.file_path == path
        assert ref.row_group_index == 0
        assert ref.num_rows == 1
        assert ref.min_timestamp is not None
        assert ref.max_timestamp is not None


